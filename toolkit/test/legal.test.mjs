// Run: node --test toolkit/test/legal.test.mjs
// Keeps the legal files honest: they exist, they link to each other and to the company policies, every web host the examples use
// is named in THIRD-PARTY-NOTICES.md, the PRIVACY.md claim "the toolkit makes no network call" is true of the code, and no dashes.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = (f) => fs.readFileSync(path.join(REPO, f), 'utf8');
const tracked = () => execFileSync('git', ['ls-files', '-z'], { cwd: REPO, encoding: 'utf8' }).split('\0').filter(Boolean);
const LEGAL = ['LICENSE', 'NOTICE', 'THIRD-PARTY-NOTICES.md', 'PRIVACY.md', 'TRADEMARKS.md', 'SECURITY.md', 'docs/LEGAL.md'];
// Built from parts so this test file does not itself name the company (the leak scan allows the name only in the notice files).
const COMPANY = ['Spar', 'cle'].join('');
const DASH = new RegExp(`[${String.fromCharCode(0x2013)}${String.fromCharCode(0x2014)}]`);

test('the legal files exist and say the essentials', () => {
	for (const f of LEGAL) assert.ok(fs.existsSync(path.join(REPO, f)), `${f} is missing`);
	assert.match(read('LICENSE'), /Apache License\s+Version 2\.0/);
	assert.match(read('NOTICE'), new RegExp(`^Bolt Apps\\nCopyright 20\\d\\d ${COMPANY} Inc\\.\\n`));   // the legal name the company terms use
	assert.equal(JSON.parse(read('toolkit/package.json')).license, 'Apache-2.0');
	assert.match(read('README.md'), /Apache License 2\.0/);
	assert.match(read('docs/LEGAL.md'), /not legal advice/i);
	assert.match(read('THIRD-PARTY-NOTICES.md'), /Nothing here is legal advice/);
	assert.match(read('TRADEMARKS.md'), /section 6/);
});

test('README has a Legal section that links every legal file, and the company policies', () => {
	const r = read('README.md');
	assert.match(r, /^## Legal$/m);
	for (const f of ['LICENSE', 'NOTICE', 'THIRD-PARTY-NOTICES.md', 'PRIVACY.md', 'TRADEMARKS.md', 'docs/LEGAL.md']) assert.ok(r.includes(`](${f})`), `README does not link ${f}`);
	for (const f of ['README.md', 'PRIVACY.md', 'docs/LEGAL.md']) { const t = read(f); assert.ok(t.includes('https://sparcle.app/privacy/'), `${f} lacks the privacy policy link`); }
	for (const f of ['README.md', 'docs/LEGAL.md']) assert.ok(read(f).includes('https://sparcle.app/terms/'), `${f} lacks the terms link`);
	assert.ok(read('SECURITY.md').includes('security@sparcle.app'));
	assert.ok(read('SECURITY.md').includes('https://sparcle.app/trust/vulnerability-disclosure/'));
});

test('every relative link in the legal files and the README resolves', () => {
	const bad = [];
	for (const f of [...LEGAL.filter((x) => x.endsWith('.md')), 'README.md', 'CONTRIBUTING.md']) {
		for (const m of read(f).matchAll(/\]\(([^)#\s]+)(#[^)]*)?\)/g)) {
			const target = m[1]; if (/^[a-z]+:/i.test(target)) continue;
			if (/^(RANKING\.md|INDEX\.json)$/.test(target)) continue;   // generated by a workflow once the gallery opens; not in the tree yet
			if (!fs.existsSync(path.resolve(REPO, path.dirname(f), target))) bad.push(`${f} -> ${target}`);
		}
	}
	assert.deepEqual(bad, []);
});

// Hosts that are not services: placeholders, local addresses, schema ids, test strings in fixtures, and sites of our own.
const NOT_A_SERVICE = /(^|\.)(example\.(com|org|net)|example|invalid|localhost)$|^(127\.|a$|x$|h$|u$|a\.com$|user$)|json-schema\.org$|(sparc)le\.app$|\.secure-verify\.github\.io$|attacker-domain\.net$|^github$|\.example\.com$/;
export function hostsUsed() {
	const found = new Map();
	for (const f of tracked()) {
		if (!/^(kit\/examples|apps)\//.test(f) || /\/golden\/|__bolt_app_kit\.py$|\.(png|gif)$/.test(f)) continue;
		const abs = path.join(REPO, f); if (!fs.existsSync(abs)) continue;
		for (const m of fs.readFileSync(abs, 'utf8').matchAll(/https?:\/\/([A-Za-z0-9.-]+)/g)) {
			const h = m[1].toLowerCase().replace(/\.$/, '');
			if (NOT_A_SERVICE.test(h)) continue;
			if (!found.has(h)) found.set(h, f);
		}
		// hosts listed without a scheme in an allowlist, such as "hosts": ["api.opentripmap.com"]
		for (const m of fs.readFileSync(abs, 'utf8').matchAll(/"((?:[a-z0-9-]+\.)+(?:com|org|net|io|edu|gov|at|es|de|dev))"/g)) if (!NOT_A_SERVICE.test(m[1]) && !found.has(m[1])) found.set(m[1], f);
	}
	return found;
}
test('every host the examples and apps use appears in THIRD-PARTY-NOTICES.md', () => {
	const notices = read('THIRD-PARTY-NOTICES.md').toLowerCase();
	const missing = [];
	for (const [h, f] of hostsUsed()) if (!notices.includes(h.replace(/^www\./, ''))) missing.push(`${h} (first seen in ${f})`);
	assert.deepEqual(missing, [], 'add each service to THIRD-PARTY-NOTICES.md with its terms link, or say why it is not a service');
});

test('every service row in THIRD-PARTY-NOTICES.md links its terms page over https', () => {
	const rows = read('THIRD-PARTY-NOTICES.md').split('\n').filter((l) => /^\| .*`[a-z0-9.-]+\.[a-z]+`/.test(l) && !l.startsWith('| Picture') && !/^\| `/.test(l));
	assert.ok(rows.length >= 12, `${rows.length} service rows`);
	for (const r of rows) assert.match(r, /<https:\/\/[^>\s]+>/, `no terms link in: ${r.slice(0, 60)}`);
});

test('PRIVACY.md is true: the toolkit code opens no network connection', () => {
	const bad = [];
	const walk = (d) => { for (const e of fs.readdirSync(path.join(REPO, d), { withFileTypes: true })) { const p = `${d}/${e.name}`; if (e.isDirectory()) walk(p); else if (/\.mjs$/.test(e.name)) {
		fs.readFileSync(path.join(REPO, p), 'utf8').split('\n').forEach((l, i) => { if (/node:(http|https|http2|net|tls|dns|dgram)\b|from ['"](http|https|net|tls|dns|dgram)['"]|\bfetch\(|XMLHttpRequest|WebSocket\(/.test(l)) bad.push(`${p}:${i + 1}`); }); } } };
	walk('toolkit/bin'); walk('toolkit/lib');
	assert.deepEqual(bad, [], 'a network call needs a row in PRIVACY.md first');
	// the one outside program the toolkit starts to read local facts is git, and it is never told to fetch
	for (const f of ['toolkit/lib/workflow.mjs']) assert.ok(!/git\(\w+, \[['"](fetch|pull|clone|ls-remote)['"]/.test(read(f)), 'git must stay local only');
	assert.match(read('PRIVACY.md'), /does not run `git fetch`/);
});

test('the legal files contain no em dash or en dash', () => {
	for (const f of [...LEGAL, 'CONTRIBUTING.md', 'README.md']) assert.ok(!DASH.test(read(f)), `${f} has a dash`);
});

test('CONTRIBUTING.md says no header is required and the hashed kit files must not change', () => {
	const c = read('CONTRIBUTING.md');
	assert.match(c, /No licence header is required/);
	assert.match(c, /never edit the kit/);
});
